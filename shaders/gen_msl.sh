# gen_msl.sh - embed the Metal Shading Language sources in shaders/ as
# C byte arrays in src/files/mtl_shaders.c.
#
# The MSL is compiled at runtime by the MTL4Compiler, so unlike
# ref_vk (which precompiles GLSL to SPIR-V with glslangValidator) we only
# need the raw source text embedded. Regenerate after editing any .msl:
#
#   sh shaders/gen_msl.sh
#
# Output is checked in (like ref_vk's spirv/*.c), so a normal build
# needs no generator: it compiles the checked-in array. "make" does
# carry one convenience rule (T4) - if some shaders/*.msl is newer
# than the generated file it regenerates in place when python3 is on
# PATH, and otherwise only warns and builds with the checked-in
# array. Freshness is enforced separately by "make check-shaders",
# which the gate (tools/fix_verify.sh) runs first and which does
# require python3.
#
# Output is written to src/files/mtl_shaders.c; an optional first
# argument redirects it (used by "make check-shaders", which compares
# against a temp file).

set -e

cd "$(dirname "$0")/.."

OUT=${1:-src/files/mtl_shaders.c}

python3 - "$OUT" <<'PYEOF'
import sys, os, glob

out_path = sys.argv[1]
msl_files = sorted(glob.glob(os.path.join("shaders", "*.msl")))

if not msl_files:
    sys.stderr.write("gen_msl.sh: no shaders/*.msl found\n")
    sys.exit(1)

def emit(name, path):
    with open(path, "rb") as f:
        data = f.read()
    lines = []
    lines.append("// AUTOGENERATED from %s by shaders/gen_msl.sh - do not edit." % path)
    lines.append("const char %s[] = {" % name)
    row = []
    for i, b in enumerate(data):
        row.append("0x%02x" % b)
        if len(row) == 12:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    # NUL terminator so the array is also a valid C string.
    row.append("0x00")
    if row:
        lines.append("    " + ", ".join(row))
    lines.append("};")
    lines.append("const size_t %s_size = sizeof(%s);" % (name, name))
    lines.append("")
    return "\n".join(lines)

with open(out_path, "w") as out:
    out.write("/*\n")
    out.write(" * Copyright (C) 2026 ref_mtl port\n")
    out.write(" *\n")
    out.write(" * This program is free software; you can redistribute it and/or modify\n")
    out.write(" * it under the terms of the GNU General Public License as published by\n")
    out.write(" * the Free Software Foundation; either version 2 of the License, or (at\n")
    out.write(" * your option) any later version.\n")
    out.write(" *\n")
    out.write(" * This program is distributed in the hope that it will be useful, but\n")
    out.write(" * WITHOUT ANY WARRANTY; without even the implied warranty of\n")
    out.write(" * MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.\n")
    out.write(" *\n")
    out.write(" * See the GNU General Public License for more details.\n")
    out.write(" *\n")
    out.write(" * You should have received a copy of the GNU General Public License\n")
    out.write(" * along with this program; if not, write to the Free Software\n")
    out.write(" * Foundation, Inc., 51 Franklin Street, Fifth Floor, Boston, MA\n")
    out.write(" * 02110-1301, USA.\n")
    out.write(" */\n\n")
    out.write("/*\n")
    out.write(" * Embedded Metal Shading Language sources (byte arrays).\n")
    out.write(" *\n")
    out.write(" * AUTOGENERATED by shaders/gen_msl.sh - do not edit by hand.\n")
    out.write(" * Regenerate with:  sh shaders/gen_msl.sh\n")
    out.write(" */\n\n")
    out.write("#include <stddef.h>\n\n")
    for path in msl_files:
        name = os.path.splitext(os.path.basename(path))[0]
        out.write(emit(name, path))

print("gen_msl.sh: wrote %s (%d shader(s))" % (out_path, len(msl_files)))
PYEOF
